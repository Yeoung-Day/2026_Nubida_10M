MAX_ATTEMPT = 4

import re  # noqa: E402 -- has_full_solution/guard_reply 에서 사용

# 완성 코드 탐지 휴리스틱 (post-guard)
# 개념/문법 교육용으로 보여주는 여러 개의 짧은 코드 예시(개별 2~3줄)까지 보호하되,
# 실제 15줄 이상의 완성 프로그램만 '완성본'으로 간주해 차단한다.
_FULL_CODE_BLOCK_MIN_LINES = 15


def build_attempt_instruction(attempt: int) -> str:
    """attempt 1~4 -> 해당 단계 지시문 (범위 밖은 4로 클램프)"""
    return ATTEMPT_INSTRUCTIONS.get(min(max(attempt, 1), MAX_ATTEMPT), ATTEMPT_INSTRUCTIONS[1])


def build_messages(
    question: str,
    attempt: int,
    similar_faqs: list[dict] | None = None,
    history: list[dict] | None = None,
    course_name: str | None = None,
) -> list[dict]:
    """
    누비다 AI 요청 메시지 조립
    similar_faqs: RAG 검색 결과 [{"question","answer","up_count","down_count"}, ...]
    history: 최근 대화 [{"role","content"}, ...] (최대 6건)
    """
    messages: list[dict] = [
        {"role": "system", "content": SYSTEM_PROMPT},
    ]

    # attempt 단계 게이트 (이중 방어 2)
    messages.append(
        {"role": "system", "content": build_attempt_instruction(attempt)}
    )

    # 강좌 컨텍스트 (있을 때만)
    if course_name:
        messages.append(
            {"role": "system", "content": f"학생이 공부 중인 강좌: {course_name} (강좌 내용에 맞춰 안내)"}
        )

    # RAG 근거 (있을 때만 -- '참고 자료'로 주입)
    if similar_faqs:
        refs = "\n".join(
            f"- Q: {f['question'][:120]}\n  A(요약): {f['answer'][:300]}"
            f"  (해결률 {_solve_rate(f.get('up_count', 0), f.get('down_count', 0))}%)"
            for f in similar_faqs[:3]
        )
        messages.append(
            {"role": "system", "content": f"과거 학생들이 비슷한 질문을 했고 아래 답변이 도움 되었습니다. "
                                          f"참고하되 같은 설명을 그대로 복사하지 말고 학생 수준에 맞게 재구성하세요:\n{refs}"}
        )

    # 최근 대화 이력 (맥락)
    if history:
        for h in history[-6:]:
            messages.append({"role": h["role"], "content": h["content"]})

    messages.append({"role": "user", "content": question})
    return messages


def _solve_rate(up: int, down: int) -> int:
    total = up + down
    return round(up * 100 / total) if total else 0


def _full_sketch_in_block(block_text: str) -> bool:
    """하나의 코드 블록 안에 setup() 과 loop() 정의가 함께(완성 스케치) 있는지."""
    has_setup = re.search(r'(?mi)^\s*(?:void\s+)?setup\s*\(', block_text)
    has_loop = re.search(r'(?mi)^\s*(?:void\s+)?loop\s*\(', block_text)
    return bool(has_setup and has_loop)


def has_full_solution(reply: str) -> bool:
    """
    post-guard: 응답에 '완성 코드'로 보이는 장문 코드 블록이 있는지 탐지
    (1) 한 블록 안에 15줄 이상 코드 = 완성본 제공 위험 -> True
    (2) 짧아도(void setup() + void loop() 가 함께 등장하는 아두이노식 완성
        스케치 블록) = 실행 가능한 완성본이므로 True
    (개념/문법 교육용 1~2줄 짧은 예시 조각은 차단하지 않는다.)
    ASCII 박스 다이어그램(주로 + 와 | 로 이루어진 도식)은 코드가 아니므로 예외 처리.
    """
    lines = reply.splitlines()
    in_code = False
    code_lines = 0
    block_buf: list[str] = []
    for ln in lines:
        if ln.strip().startswith("```"):
            if in_code:
                # 블록 종료: 완성 스케치 시그니처 검사 (길이 무관)
                block_text = "\n".join(block_buf)
                if _full_sketch_in_block(block_text):
                    return True
                if code_lines >= _FULL_CODE_BLOCK_MIN_LINES:
                    return True
            in_code = not in_code
            code_lines = 0
            block_buf = []
        elif in_code:
            stripped = ln.strip()
            ascii_box = (
                stripped.startswith("+") or stripped.startswith("|")
                or bool(re.match(r"^[+\-/|:=<>\\_]+$", stripped))
            )
            if not ascii_box:
                code_lines += 1
                block_buf.append(ln)
    # 문서 끝에 코드 블록이 닫히지 않은 채 남은 경우 마지막 블록 검사
    if in_code and block_buf:
        block_text = "\n".join(block_buf)
        if _full_sketch_in_block(block_text):
            return True
    return False


def guard_reply(reply: str, attempt: int) -> str:
    """
    post-guard 적용:
      1) 완성 코드 탐지 시 코드 블록 잘라내고 단계에 맞는 힌트만 유지
      2) LLM이 쓴 마크다운 특수문자를 학습자 친화적으로 정리
      3) 형광펜용 이중 별표는 유지, 프론트에서 mark 태그로 변환
    """
    # 1) 완성 코드 탐지
    #    - 완성 스케치(setup()~loop()) 블록: 실행 가능한 '해답'이므로 코드 전체 제거
    #    - 그 외 15줄 이상 장문 블록: 앞부분 일부만 남기고 요약 (개념 설명이 과하게 잘리는 것 방지)
    had_full = has_full_solution(reply)
    if had_full:
        out_lines: list[str] = []
        in_code = False
        code_kept = 0
        block_buf = []
        for ln in reply.splitlines():
            if ln.strip().startswith("```"):
                if in_code:
                    blk_text = "\n".join(block_buf)
                    is_sketch = _full_sketch_in_block(blk_text)
                    if is_sketch:
                        out_lines.append("(실행 가능한 완성 코드는 제공하지 않아요. 직접 조립해 보세요)")
                    elif code_kept < 10:
                        # 일반 15줄+ 장문: 앞부분 보존
                        for k in range(min(10, len(block_buf))):
                            out_lines.append(block_buf[k])
                        if len(block_buf) > 10:
                            out_lines.append("(이어지는 코드는 학습용 요약으로 대체)")
                in_code = not in_code
                code_kept = 0
                block_buf = []
                continue
            if in_code:
                code_kept += 1
                block_buf.append(ln)
                continue
            out_lines.append(ln)
        reply = "\n".join(out_lines).strip()

    # 2) 일반 마크다운 특수문자 정리 (단, **형광펜**과 [SVG] 블록은 유지)
    import re
    # SVG 블록을 임시로 마스킹 (특수문자 정리로부터 보호)
    svg_blocks = []
    def _mask_svg(m):
        idx = len(svg_blocks)
        svg_blocks.append(m.group(0))
        return f"\u0000SVG{idx}\u0000"
    reply = re.sub(r'\[SVG\].*?\[/SVG\]', _mask_svg, reply, flags=re.DOTALL)
    # ## heading -> 특수문자 제거 (제목 자체는 유지)
    reply = re.sub(r'^#{1,6}\s+', '', reply, flags=re.MULTILINE)
    # > 인용구 -> "💡 " 접두사
    reply = re.sub(r'^>\s*', '💡 ', reply, flags=re.MULTILINE)
    # 단일 *기울임* -> 제거 (형광펜 이중 ** 방해하지 않게 * 하나만)
    reply = re.sub(r'(?<!\*)\*(?!\*)([^*\n]+)(?<!\*)\*(?!\*)', r'\1', reply)
    # `코드` -> 일반 텍스트로 (프론트에서 code 변환)
    reply = re.sub(r'`([^`\n]+)`', r'`\1`', reply)
    # ~~취소선~~ -> 제거
    reply = re.sub(r'~~([^~]+)~~', r'\1', reply)
    # --- 구분선 -> 빈 줄
    reply = re.sub(r'^---+$', '', reply, flags=re.MULTILINE)
    # SVG 블록 복원
    for idx, blk in enumerate(svg_blocks):
        reply = reply.replace(f"\u0000SVG{idx}\u0000", blk)

    # 3) 완성 코드였던 경우 안내문 추가
    if had_full:
        reply += "\n\n💡 완성 코드 대신 해결방법을 안내해 드려요. 아래 단서로 직접 완성해 보세요. 그래도 어렵다면 [⚠️ 부족]을 눌러 더 자세한 힌트를 받을 수 있어요."

    return reply.strip()
